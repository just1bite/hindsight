#!/usr/bin/env bash
# Auto-generate .env with secure keys
# Usage: ./setup-env.sh

set -euo pipefail

ENV_FILE=".env"

if [[ -f "$ENV_FILE" ]]; then
    echo "ERROR: $ENV_FILE already exists"
    echo "Backup it first: mv $ENV_FILE ${ENV_FILE}.backup-$(date +%s)"
    exit 1
fi

# Generate secure keys
SECRET_KEY=$(openssl rand -hex 32)
API_KEY=$(openssl rand -hex 32)
PASSWORD=$(openssl rand -base64 16 | tr -d '/+=' | cut -c1-16)

# Read LLM config from .env.example or use defaults
LLM_PROVIDER="${LLM_PROVIDER:-openai}"
LLM_MODEL="${LLM_MODEL:-gpt-4o-mini}"
LLM_BASE_URL="${LLM_BASE_URL:-https://api.openai.com/v1}"
LLM_API_KEY="${LLM_API_KEY:-your-llm-api-key}"

# Create .env
cat > "$ENV_FILE" << ENVEOF
# Generated by setup-env.sh on $(date -Iseconds)
# LLM Provider (OpenAI-compatible)
HINDSIGHT_API_LLM_PROVIDER=${LLM_PROVIDER}
HINDSIGHT_API_LLM_API_KEY=${LLM_API_KEY}
HINDSIGHT_API_LLM_MODEL=${LLM_MODEL}
HINDSIGHT_API_LLM_BASE_URL=${LLM_BASE_URL}

# Auth (required for production)
# AUTH_SECRET_KEY: JWT signing key (generate with: openssl rand -hex 32)
# AUTH_API_KEY: Bearer token for external API agents
AUTH_ENABLED=true
AUTH_USERNAME=admin
AUTH_PASSWORD=${PASSWORD}
AUTH_SECRET_KEY=${SECRET_KEY}
AUTH_API_KEY=${API_KEY}

# Optional: Control Plane access key (alternative to username/password)
# HINDSIGHT_CP_ACCESS_KEY=your-shared-secret
ENVEOF

chmod 600 "$ENV_FILE"

echo "✓ Created .env with secure keys"
echo ""
echo "Credentials:"
echo "  Username: admin"
echo "  Password: ${PASSWORD}"
echo "  API Key:  ${API_KEY:0:8}...${API_KEY: -4}"
echo "  Secret:   ${SECRET_KEY:0:8}...${SECRET_KEY: -4}"
echo ""
echo "⚠️  Securely store the API key and password for agent integration"
